/// Look up an instruction definition by opcode (binary search).
pub fn definition_for_opcode(opcode: u32) -> Option<&'static InstructionDefinition> {
    OPCODE_TABLE
        .binary_search_by_key(&opcode, |def| def.opcode)
        .ok()
        .map(|idx| &OPCODE_TABLE[idx])
}

/// Look up an instruction definition by label (linear scan).
pub fn definition_for_label(label: &str) -> Option<&'static InstructionDefinition> {
    OPCODE_TABLE.iter().find(|def| def.label == label)
}

/// Returns true if this opcode is a control flow instruction whose arguments
/// may reference code locations (labels).
pub fn is_control_flow(opcode: u32) -> bool {
    matches!(
        opcode,
        0x8C | 0x8F | 0xA0 | 0xCC | 0xFB | 0xD4 | 0x90 | 0x7B
    )
}

/// Returns true if the argument at index `arg_idx` in the given instruction
/// is a label reference (code location pointer).
pub fn is_label_argument(opcode: u32, arg_idx: usize, raw_data: u32) -> bool {
    match opcode {
        // jmp, call: all args are labels (if not 0xFFFFFFFF)
        0x8C | 0x8F => raw_data != 0xFFFFFFFF,
        // jcc: args after index 0 are labels
        0xA0 => arg_idx > 0 && raw_data != 0xFFFFFFFF,
        // mouse_callback, joy_callback: args after index 0 are labels
        0xCC | 0xFB => arg_idx > 0 && raw_data != 0xFFFFFFFF,
        // u004266F0: args at index >= 2 are labels
        0xD4 => arg_idx >= 2 && raw_data != 0xFFFFFFFF,
        // u0041BEB0: args at index >= 4 are labels
        0x90 => arg_idx >= 4 && raw_data != 0xFFFFFFFF,
        // u0041ADB0: all args are labels
        0x7B => raw_data != 0xFFFFFFFF,
        _ => false,
    }
}

