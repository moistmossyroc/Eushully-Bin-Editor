#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_opcode_table_is_sorted() {
        for window in OPCODE_TABLE.windows(2) {
            assert!(
                window[0].opcode < window[1].opcode,
                "Opcode table not sorted: 0x{:X} >= 0x{:X}",
                window[0].opcode,
                window[1].opcode
            );
        }
    }

    #[test]
    fn test_lookup_show_text() {
        let def = definition_for_opcode(0x6E).unwrap();
        assert_eq!(def.label, "show-text");
        assert_eq!(def.argument_count, 2);
    }

    #[test]
    fn test_lookup_by_label() {
        let def = definition_for_label("end-text-line").unwrap();
        assert_eq!(def.opcode, 0x6F);
        assert_eq!(def.argument_count, 1);
    }

    #[test]
    fn test_control_flow() {
        assert!(is_control_flow(0x8C)); // jmp
        assert!(is_control_flow(0x8F)); // call
        assert!(is_control_flow(0xA0)); // jcc
        assert!(!is_control_flow(0x6E)); // show-text
    }

    #[test]
    fn test_label_arguments() {
        // jmp: arg 0 is a label
        assert!(is_label_argument(0x8C, 0, 0x100));
        assert!(!is_label_argument(0x8C, 0, 0xFFFFFFFF));
        // jcc: arg 0 is NOT a label, args 1+ are
        assert!(!is_label_argument(0xA0, 0, 0x100));
        assert!(is_label_argument(0xA0, 1, 0x100));
    }
}
